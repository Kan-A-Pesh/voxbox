//! Writes the built-in voices and the effect catalog as typed TypeScript modules for the UI's browser
//! mock (`ui/src/ipc/generated/`). Run after changing presets or the catalog:
//! `cargo run -p voxbox-dsp --example dump_presets -- ui/src/ipc/generated`

use std::path::PathBuf;

fn main() -> std::io::Result<()> {
    let dir = PathBuf::from(
        std::env::args()
            .nth(1)
            .unwrap_or_else(|| "ui/src/ipc/generated".into()),
    );
    std::fs::create_dir_all(&dir)?;
    let presets = serde_json::to_string_pretty(&voxbox_dsp::builtin_presets())?;
    let catalog = serde_json::to_string_pretty(&voxbox_dsp::effect_catalog())?;
    std::fs::write(
        dir.join("presets.ts"),
        module("BUILTIN_PRESETS", "VoicePreset", &presets),
    )?;
    std::fs::write(
        dir.join("catalog.ts"),
        module("EFFECT_CATALOG", "EffectDescriptor", &catalog),
    )?;
    println!("écrit dans {}", dir.display());
    Ok(())
}

/// A typed TS module so `tsc` checks the generated data against the contract.
pub fn module(name: &str, ty: &str, json: &str) -> String {
    format!(
        "// Generated by `cargo run -p voxbox-dsp --example dump_presets`. Do not edit.\n\
         import type {{ {ty} }} from \"../contract\";\n\n\
         export const {name}: {ty}[] = {json};\n"
    )
}
